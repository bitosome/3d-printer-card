function touch(surface, type, points) {
  Object.defineProperties(surface, { clientWidth: { value: 400, configurable: true }, clientHeight: { value: 200, configurable: true } });
  const event = new Event(type, { cancelable: true, bubbles: true });
  Object.defineProperty(event, "touches", { value: points.map(([clientX, clientY]) => ({ clientX, clientY })) });
  surface.dispatchEvent(event);
  return event;
}
function pinch(surface) {
  touch(surface, "touchstart", [[100, 100], [200, 100]]);
  return touch(surface, "touchmove", [[50, 100], [250, 100]]);
}
assert.equal(pinch(root.querySelector(".camera-viewport")).defaultPrevented, false);
assert.ok(root.querySelector(".camera-media").style.transform.includes("scale(1)"));
console.log("PASS: embedded feed leaves page gestures available");
